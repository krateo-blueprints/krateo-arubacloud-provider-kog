#!/usr/bin/env python3
"""Generate the Composition chart's per-kind facts from the same source as samples/.

The chart used to hard-code three things the generators already know, and all three
drifted silently until a server-side dry run caught them:

  1. the resource `apiVersion` -- it said `v1alpha1`, but a resource CRD is served at
     the version derived from its document's `info.version` (1.0.0 -> v1-0-0). Only
     the companion <Kind>Configuration CRD is v1alpha1. `crd_version()` in
     gen_samples_and_coverage.py already records that samples hit exactly this
     rejection and were fixed; the chart never was.
  2. the `authentication` block -- it said `bearer` for every kind, but Aruba
     declares `apiKey` in eight of its thirteen documents and `http`/`bearer` in the
     other five, so Vpc/Subnet/SecurityGroup need apiKey with a `Bearer ` valuePrefix
     while CloudServer needs bearer. (Reported upstream as Arubacloud/api#22.)
  3. the per-verb query config -- it emitted all five verbs for every kind, but
     CloudServer's create/update/delete are delegated to Snowplow RESTActions, so its
     Configuration CRD has no query entries for them and strict decoding refuses them.

So the chart is no longer told these; it asks. This script writes
`templates/_generated.tpl`, the hand-written templates `include` it, and
`scripts/validate.py` fails if the file on disk differs from what this would write --
the same contract the rest of the generated tree has.

The chart's structure, values and layout stay hand-authored. Only the facts that
drift are derived.
"""

import json
import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_samples_and_coverage import FILES, auth_block, crd_version, load_rds  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OAS = os.path.join(ROOT, "openapi")
CHART = os.path.join(ROOT, "compositions", "aruba-network-environment")
OUT = os.path.join(CHART, "templates", "_generated.tpl")

# The kinds this composition fans out into. Order is the order they are created in.
#
# CloudServer is deliberately NOT here, and the ORIGINAL REASON NO LONGER APPLIES.
# It used to be that its create lives only in compute-provider_v1.1.json, reachable
# only through a per-verb oasPath the controller ignored, so on the 0.27.1 pin the
# CRD's spec was exactly {configurationRef, metadata.name, projectId} and a
# composition could create an object but not a server. oasgen#227 shipped in 0.34.0,
# the RestDefinition carries the per-verb oasPath, and the spec is complete -- so
# "it returns when the pin moves" was wrong, and the pin has moved twice since.
#
# It stays out because of two things a composition cannot assume:
#   * update and delete are delegated to Snowplow RESTActions, which need snowplow
#     AND authn plus a projected token and an authn allowlist CR -- four
#     prerequisites the oasgen-provider chart does not provide. Without them the
#     resource wedges on its finalizer rather than failing cleanly.
#   * create is refused on a trial account: Aruba answers
#     {"fieldName":"FlavorId","errorMessage":"<id> not available for trial"} and the
#     flavor catalog exposes only {name, cpu, ram}, so eligibility is not
#     discoverable before the attempt.
KINDS = ["Vpc", "Subnet", "SecurityGroup"]

GROUP = "arubacloud.ogen.krateo.io"
# The <Kind>Configuration CRD is NOT versioned from info.version; it is always this.
CONFIG_VERSION = "v1alpha1"

HEADER = """{{/*
  GENERATED by scripts/gen_composition.py -- do not edit.

  Per-kind facts derived from the vendored OAS documents and the generated
  RestDefinitions, so the chart cannot drift from the CRDs it creates resources
  against. Run the script to refresh; validate.py fails if this file is stale.
*/}}
"""


def facts():
    """kind -> {apiVersion, auth, verbs}, derived, never typed."""
    by_kind = {}
    for prov, doc in load_rds():
        res = (doc.get("spec") or {}).get("resource") or {}
        by_kind[res.get("kind")] = (prov, res)

    specs = {}
    out = {}
    for kind in KINDS:
        if kind not in by_kind:
            raise SystemExit(f"{kind} has no RestDefinition -- the composition "
                             f"references a resource this repo does not generate")
        prov, res = by_kind[kind]
        if prov not in specs:
            with open(os.path.join(OAS, FILES[prov])) as fh:
                specs[prov] = json.load(fh)
        spec = specs[prov]
        out[kind] = {
            "apiVersion": f"{GROUP}/{crd_version(spec)}",
            "auth": auth_block(spec),
            # Exactly the verbs this resource's Configuration CRD will accept. A verb
            # delegated to a RESTAction via *ApiRef has no query entry, and sending
            # one is a strict-decoding error, not a no-op.
            "verbs": [v["action"] for v in res.get("verbsDescription", [])],
        }
    return out


def render_auth(block):
    """The auth block as Helm-templated YAML: shape from the OAS, Secret from values."""
    (scheme, body), = block.items()
    lines = [f"  {scheme}:",
             "    tokenRef:",
             '      name: {{ .Values.tokenSecret.name | quote }}',
             '      namespace: {{ .Values.tokenSecret.namespace | quote }}',
             '      key: {{ .Values.tokenSecret.key | quote }}']
    for key in ("header", "valuePrefix"):
        if key in body:
            # json.dumps, NOT yaml.safe_dump: dumping a bare scalar yields
            # "Authorization\n...\n" -- the YAML document-end marker -- and that
            # "..." landed in the template and broke the render. JSON scalars are
            # valid YAML and double-quoting preserves valuePrefix's trailing space,
            # which is load-bearing ("Bearer " + token).
            lines.append(f"    {key}: {json.dumps(body[key])}")
    return "\n".join(lines)


def main():
    data = facts()
    parts = [HEADER]
    for kind, f in data.items():
        parts.append(
            f'{{{{- define "aruba.gen.apiVersion.{kind}" -}}}}{f["apiVersion"]}'
            f'{{{{- end -}}}}\n')
        parts.append(
            f'{{{{- define "aruba.gen.configApiVersion.{kind}" -}}}}'
            f'{GROUP}/{CONFIG_VERSION}{{{{- end -}}}}\n')
        parts.append(
            f'{{{{- define "aruba.gen.auth.{kind}" -}}}}\n'
            f'authentication:\n{render_auth(f["auth"])}\n'
            f'{{{{- end -}}}}\n')
        parts.append(
            f'{{{{- define "aruba.gen.verbs.{kind}" -}}}}'
            f'{",".join(f["verbs"])}{{{{- end -}}}}\n')
    # The kind list itself, so the templates cannot loop over a set that differs
    # from the one these facts were generated for -- which is exactly what broke
    # when CloudServer was dropped from KINDS and configurations.yaml kept it.
    parts.append(f'{{{{- define "aruba.gen.kinds" -}}}}{",".join(data)}{{{{- end -}}}}\n')
    body = "\n".join(parts)

    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != body:
            print(f"STALE: {os.path.relpath(OUT, ROOT)} differs from what "
                  f"gen_composition.py would write -- run it", file=sys.stderr)
            return 1
        print(f"{os.path.relpath(OUT, ROOT)} is up to date")
        return 0

    with open(OUT, "w") as fh:
        fh.write(body)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    for kind, f in data.items():
        print(f"  {kind:<16} {f['apiVersion']:<38} "
              f"auth={next(iter(f['auth'])):<7} verbs={','.join(f['verbs'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
